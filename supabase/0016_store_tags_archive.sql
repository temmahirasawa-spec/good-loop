-- GOOD REVIEW: アンケート項目のアーカイブ（消さずに隠す）
--
-- 背景（2026-08-24、天真の決定）: これまで「回答が付いた項目は削除できない」
-- （response_tags.tag_id の on delete restrict で 409 エラー）という制約があり、
-- 「項目は自由に変えられます」という案内と食い違っていた（docs/specs/onboarding.md の既知の制約）。
--
-- 一般的なアーカイブ方式に切り替える（Google Forms 等と同じ「過去の回答データは不変」の思想）:
--   ・削除       = archived_at を立てて隠す。来店客に出ず、新しい回答も付かない。
--                  過去の集計は集計画面にそのまま残る
--   ・名前の変更 = 旧項目をアーカイブ ＋ 新項目を0から。
--                  例:「接客」→「接客・スタッフ」なら、「接客」の集計は残ったまま止まり、
--                  「接客・スタッフ」が0から数え始める
--   ・同じ名前で作り直し = アーカイブ済みがあれば復元（集計が続きから再開する）
--
-- ⚠ **列の追加のみ。既存の列・データは1つも書き換えない。**
--    on delete restrict も外さない（アーカイブ運用では delete は「未使用の項目」にしか
--    走らないため、restrict が発火することは無くなる。最後の砦として残す）。
--
-- 1機能1ファイル（CLAUDE.md 4章）。

alter table store_tags add column if not exists archived_at timestamptz;

comment on column store_tags.archived_at is
  'アーカイブした日時。null なら現役。アーカイブ済みは来店客に出ず、新しい回答も付かないが、過去の集計は残る';
