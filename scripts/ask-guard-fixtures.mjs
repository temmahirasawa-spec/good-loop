let failed = 0;
for (const [name, input, output, expected, avoid = []] of CASES) {
  const verdict = guardQuestion(input, output, avoid);
  const got = verdict.ok;
  const mark = got === expected ? "  OK  " : "* NG *";
  if (got !== expected) failed++;
  const reason = verdict.ok ? "" : `（${verdict.reason}）`;
  console.log(`${mark} ${name}\n       入力: ${input}\n       問い: ${output.replace(/\n/g, "⏎")}\n       判定: ${got ? "通す" : "捨てる"}${reason} / 期待: ${expected ? "通す" : "捨てる"}`);
}

console.log(`\n${CASES.length}件中 ${CASES.length - failed}件が期待どおり`);
if (failed > 0) {
  console.error(`✗ ${failed}件が期待と違います`);
  process.exit(1);
}
console.log("✓ 検査層は期待どおりに動いています");
